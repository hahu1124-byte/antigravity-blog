// 段数のある前兆を「段の並び」と値の表から作る。"小→中→大" なら 小・中 が当該より前の変動の段、
// 大 が当該の段。steps：段の名前 → { code（id 用の記号）, text, color, fx }。
// rows：[段の並び, 信頼度, share, 追加の項目]。extra は全部の状態に付ける項目（reaches など）
function evaStepStates(idHead, label, steps, rows, extra = {}) {
  return rows.map(([seq, trust, share, more]) => {
    const parts = seq.split("→");
    const last = steps[parts[parts.length - 1]];
    return {
      id: idHead + "-" + parts.map((p) => steps[p].code).join(""),
      name: `${label}(${seq})`,
      trust,
      share,
      lead: parts.slice(0, -1).map((p) => steps[p]),
      text: last.text,
      ...(last.color ? { color: last.color } : {}),
      ...(last.fx ? { fx: last.fx } : {}),
      ...extra,
      ...(more || {}),
    };
  });
}

// 名前と値の表から、段の無い演出をまとめて作る（モニターSU のセリフ別・パネルの組合せ別など）。
// rows：[id の後ろ, 名前の括弧の中, 信頼度, share（extra.amount が "rate" なら rate）, 追加の項目]
function evaRowStates(idHead, label, rows, extra = {}) {
  const { amount = "share", ...rest } = extra;
  return rows.map(([code, what, trust, value, more]) => ({
    id: idHead + "-" + code,
    name: `${label}(${what})`,
    trust,
    [amount]: value,
    ...rest,
    ...(more || {}),
  }));
}

